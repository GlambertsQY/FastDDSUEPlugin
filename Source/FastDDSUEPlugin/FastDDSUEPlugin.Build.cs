using System.IO;
using UnrealBuildTool;

public class FastDDSUEPlugin : ModuleRules
{
	public FastDDSUEPlugin(ReadOnlyTargetRules Target) : base(Target)
	{
		PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;
		bUseRTTI = true;
		bEnableExceptions = true;

		PublicIncludePaths.Add(Path.Combine(ModuleDirectory, "include"));

		// Static linking: disable eProsima auto-link pragmas.
		PublicDefinitions.Add("FASTRTPS_NO_LIB");
		PublicDefinitions.Add("FASTCDR_NO_LIB");
		PublicDefinitions.Add("FOONATHAN_MEMORY=1");
		PublicDefinitions.Add("FOONATHAN_MEMORY_VERSION_MAJOR=0");
		PublicDefinitions.Add("FOONATHAN_MEMORY_VERSION_MINOR=7");
		PublicDefinitions.Add("FOONATHAN_MEMORY_VERSION_PATCH=3");

		// eProsima headers use the macros below in #if expressions without defining them,
		// which fails UE's C4668 (Windows) / -Wundef (Android) checks.
		PublicDefinitions.Add("__APPLE__=0");
		PublicDefinitions.Add("__FreeBSD__=0");
		PublicDefinitions.Add("__VXWORKS__=0");
		PublicDefinitions.Add("__INTERNALDEBUG=0");
		PublicDefinitions.Add("_INTERNALDEBUG=0");
		// fastrtps/config.h evaluates FASTCDR_VERSION_MAJOR without including fastcdr/config.h.
		// Must match the bundled Fast CDR major version (identical redefinition is benign).
		PublicDefinitions.Add("FASTCDR_VERSION_MAJOR=2");

		if (Target.Platform == UnrealTargetPlatform.Win64)
		{
			PublicDefinitions.Add("WIN32");
			PublicDefinitions.Add("_WINDOWS");
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "win64", "libfastcdr-2.2.lib"));
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "win64", "libfastrtps-2.14.lib"));
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "win64", "foonathan_memory-0.7.3.lib"));
			PublicSystemLibraries.Add("ShLwApi.lib");
			PublicSystemLibraries.Add("Iphlpapi.lib");
		}
		else if (Target.Platform == UnrealTargetPlatform.Android)
		{
			PublicDefinitions.Add("ANDROID");
			// fastcdr/config.h in include/ was generated by the Win64 build (sizeof(long double) == 8).
			// Android arm64 uses a 128-bit long double; the header macro is #ifndef-guarded.
			PublicDefinitions.Add("FASTCDR_SIZEOF_LONG_DOUBLE=16");
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "android_arm64", "libfastcdr.a"));
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "android_arm64", "libfastrtps.a"));
			PublicAdditionalLibraries.Add(Path.Combine(ModuleDirectory, "libs", "android_arm64", "libfoonathan_memory-0.7.3.a"));
		}

		PublicDependencyModuleNames.AddRange(
			new string[]
			{
				"Core",
			}
			);

		PrivateDependencyModuleNames.AddRange(
			new string[]
			{
				"CoreUObject",
				"Engine",
				"Slate",
				"SlateCore",
			}
			);
	}
}
